export function configProblems(values = process.env) {
  const problems = [];
  try {
    const url = new URL(values.APP_URL);
    const local = ['localhost', '127.0.0.1', '[::1]'].includes(url.hostname);
    if ((url.protocol !== 'https:' && !(local && url.protocol === 'http:')) ||
        url.username || url.password || url.pathname !== '/' || url.search || url.hash) throw new Error();
  } catch { problems.push('APP_URL must be the HTTPS site origin. Local HTTP is allowed for testing.'); }
  for (const name of ['DB_HOST', 'DB_NAME', 'DB_USER', 'DB_PASSWORD']) {
    if (!values[name]?.trim()) problems.push(`${name} is required.`);
  }
  if (values.DB_PORT && (!/^\d+$/.test(values.DB_PORT) || Number(values.DB_PORT) < 1 || Number(values.DB_PORT) > 65535))
    problems.push('DB_PORT must be a valid port.');
  if (values.ADMIN_EMAIL && !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(values.ADMIN_EMAIL)) problems.push('ADMIN_EMAIL must be a valid bootstrap owner email when supplied.');
  if (values.ADMIN_PASSWORD_HASH && !/^scrypt\$[A-Za-z0-9_-]{22}\$[A-Za-z0-9_-]{43}$/.test(values.ADMIN_PASSWORD_HASH))
    problems.push('ADMIN_PASSWORD_HASH must be generated by npm run hostinger:secrets.');
  if ((values.SESSION_SECRET?.length ?? 0) < 32 || /^(replace|change|example)/i.test(values.SESSION_SECRET ?? ''))
    problems.push('SESSION_SECRET must be a random secret of at least 32 characters.');
  try {
    if (!/^[A-Za-z0-9+/]{43}=$/.test(values.BILLING_ENCRYPTION_KEY ?? '') || Buffer.from(values.BILLING_ENCRYPTION_KEY, 'base64').length !== 32)
      throw new Error();
  } catch { problems.push('BILLING_ENCRYPTION_KEY must be a base64-encoded 32-byte key.'); }
  if (values.SESSION_SECRET && values.SESSION_SECRET === values.BILLING_ENCRYPTION_KEY) problems.push('Use different session and encryption secrets.');
  return problems;
}

export function requireConfig() {
  const problems = configProblems();
  if (problems.length) throw new Error('Hostinger setup is incomplete.');
  return process.env;
}

export function emailConfigProblems(values = process.env) {
  const problems = [];
  if (!/^re_[A-Za-z0-9_-]{8,}$/.test(values.RESEND_API_KEY ?? '')) problems.push('RESEND_API_KEY is required for owner sign-in emails.');
  const sender = values.AUTH_EMAIL_FROM ?? '';
  const wrapped = /^(?:[^<>\r\n]{1,100} )?<([^<>\r\n]+)>$/.exec(sender);
  const address = wrapped ? wrapped[1] : sender;
  if (sender.length > 254 || /[\r\n]/.test(sender) || !/^[^\s<>@]+@[^\s<>@]+\.[^\s<>@]+$/.test(address))
    problems.push('AUTH_EMAIL_FROM must be a verified sender address.');
  return problems;
}
